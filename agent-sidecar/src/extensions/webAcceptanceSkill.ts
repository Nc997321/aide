import { builtinSkillPath, ensureBuiltinSkill, type SkillEnv } from "./builtinSkill.js";

/**
 * web-acceptance skill 自动落地（内建，免用户配置）：**开发完成后**对网页功能做验收走查的流程。
 *
 * 动机（用户 2026-10-14 反馈）：agent 用内置浏览器走查时想到哪测到哪——筛选没走全、新增 / 修改后
 * 不回读核对数据、没测的项不说。浏览器工具本身够用，缺的是测试纪律：覆盖清单、三方对账
 * （请求 / 响应 / 页面）、写后回读、报告必须交代未测项。
 *
 * # 触发边界（description 的措辞是本文件最要紧的部分）
 *
 * **只在「开发完了，测一下 / 走查 / 验收」时触发**。探查式的请求（「看看这个按钮」「这页为什么是空的」）
 * 几步就完，套一整套验收流程是负担——用户明确要求这类请求不走本 skill。工具怎么用归
 * browser-inspect，本 skill 只管流程，不重复工具说明。
 *
 * # 不出现站点名词
 *
 * 同 browser-inspect：这里只写通用测试方法。项目的测试账号、业务规则、禁碰操作住在项目自己的
 * CLAUDE.md 或用户给的文档里。
 */

const SKILL_NAME = "web-acceptance";

export function webAcceptanceSkillPath(env: SkillEnv): string {
  return builtinSkillPath(env, SKILL_NAME);
}

export const WEB_ACCEPTANCE_SKILL_CONTENT = `---
name: web-acceptance
description: Use ONLY after building or changing a web feature, when the user asks to test / walk through / accept it (开发完了测一下、走查、验收). Not for exploratory checks like one button or a blank page.
---

# 开发完成后的验收走查

## 先判断该不该用这套流程

只在这种情况下按本流程走：**刚开发或修改完一个网页功能，用户要求测试、走查或验收它。**

用户只是让你看一下某个按钮、查一下某个页面、定位一个现象，那是探查：几步做完、直接回答，**不要**套用本流程，也不要写验收报告。拿不准就问一句：「要完整验收走查，还是只看这一处？」

浏览器工具怎么用见 browser-inspect 技能，本文只讲测试流程。项目自己的测试账号、业务规则、不能碰的操作，查项目的 CLAUDE.md 或用户给的文档。

## 一、先列清单，再动手

1. **定范围**：从本次改动出发（git diff、用户的描述、需求文档），找出改动波及的页面和接口。改动没碰的老功能不必全测，但共用了被改组件或接口的地方要测。
2. **列用例**：对范围内每个页面先 browser_read，把可测面逐项列成用例，记进任务清单（TodoWrite）。逐类过一遍，别凭印象挑：
   - 每一个筛选条件：单独用、组合用、清空 / 重置；
   - 排序、分页，以及翻页后筛选条件是否还在；
   - 列表的每一列：格式、空值、枚举值的显示；
   - 新增：必填校验、格式校验、成功路径；
   - 修改：回显是否正确、改后保存；
   - 删除：确认框、删后列表与总数；
   - 其余每个操作：导出、批量、状态切换、按状态 / 权限禁用的按钮。
3. **先把清单简短列给用户，再开始执行。**

## 二、一条用例怎么才算「测过」

「页面看起来对了」不算。每条用例都要对上三处：

- **请求**：browser_network 里的请求参数，是不是你刚才的操作（筛选值、分页参数、表单字段名和值）；
- **响应**：状态码和返回的数据；
- **页面**：browser_read 读到的，是不是就是返回的数据（条数、字段值、格式）。

筛选的通过标准是**返回的每一行都满足条件**，不是「列表变了」。结果为空时，要确认是真的没有数据而不是出错了：换一个肯定有结果的条件对照一次。

操作没有触发任何请求，就在结果里写明「纯前端行为」。

## 三、写操作必须回读

「保存成功」的提示不是证据，回读到的数据才是。

- **新增后**：回到列表，用筛选或搜索把这条找出来，逐字段和你填的值比对；再打开详情或编辑页比对一次。
- **修改后**：刷新页面（navigate 到当前地址）再读，确认改动已经持久化，不是前端残留的状态；改了的字段变了，没改的字段没有被冲掉。
- **删除后**：刷新确认它消失了，总数变化正确。
- **失败路径**：至少测一个必填为空、一个格式非法，确认被拦住，并看清是前端拦的（没发请求）还是后端拒的（请求返回了错误）。

## 四、写数据的边界

- 用户要求验收走查，就是授权你在**当前测试环境**新增、修改、删除**测试数据**。
- 地址看起来像生产环境（没有 localhost、test、dev、staging 之类的字样，用户也没说过这是测试环境），**先问，不写**。
- 自己造的数据要认得出来，名称里带「走查」之类的标记。
- **只动自己造的数据**：测修改和删除时，先新增一条，再对它操作；不改别人已有的数据。
- 收尾时删掉自己造的数据，删不掉的在报告里列出来。
- 不碰：真实支付、给真实对象发短信 / 邮件、不可逆的批量操作。这些列进「未测」并写明原因。

## 五、发现问题时

- 记下步骤、期望、实际、证据（请求编号、响应片段、页面上的文本）。
- 判断问题在哪一端：请求参数错是前端；参数对、返回错是后端；返回对、显示错是前端渲染。
- 默认只报告不修；用户说了「测完顺便修」再修，修完重跑受影响的用例。
- 一个问题不要卡住整个走查，记下来继续测其余用例。

## 六、报告：三部分，缺一不可

**已测**：表格，列出用例、结果（通过 / 失败）、证据。

**未测**：逐条写原因。常见原因：缺测试数据、没有所需的账号或权限、涉及真实支付或通知、页面报错走不下去、超出本次范围。

**问题**：按严重程度排列，每条带复现步骤和证据。

最后一行交代测试数据的清理情况。

硬规则：

- **清单里的每一条，都必须出现在「已测」或「未测」里**，一条都不能悄悄消失。
- 只有清单全部在「已测」且全部通过，才可以说「全部通过」。

## 不要这样做

- 只测成功路径。
- 用 browser_eval 直接改页面或调接口来「完成」用例：那测的不是页面。操作一律用 browser_act 走真实界面，eval 只用来读状态。
- 用截图代替读数据：截图看不出字段值对不对。
`;

/** 幂等落地：内容不同才写。任何失败都跳过，不影响会话。 */
export function ensureWebAcceptanceSkill(env: SkillEnv): void {
  ensureBuiltinSkill(env, SKILL_NAME, WEB_ACCEPTANCE_SKILL_CONTENT);
}
