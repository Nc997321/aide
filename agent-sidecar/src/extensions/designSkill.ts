import { builtinSkillPath, ensureBuiltinSkill, type SkillEnv } from "./builtinSkill.js";

/**
 * aide-design skill 自动落地（内建，免用户配置）：agent 产出「给人看的网页」时的设计方法。
 *
 * 三类产出共用这一份：侧栏应用的界面（aide-app）、单文件 HTML 幻灯片（欢迎页「幻灯片」
 * 场景）、独立的 HTML 页面（报告 / 原型 / 介绍页）。这里只讲通用的设计判断；各自的工程
 * 约束（清单、沙箱、翻页）留在各自的 skill / 场景指引里，由它们指过来，不在这里重复。
 */

const SKILL_NAME = "aide-design";

export function designSkillPath(env: SkillEnv): string {
  return builtinSkillPath(env, SKILL_NAME);
}

export const DESIGN_SKILL_CONTENT = `---
name: aide-design
description: Use BEFORE writing the HTML/CSS of anything a person will look at — an Aide sidebar app's UI, an HTML slide deck, a standalone HTML page such as a report, prototype, dashboard or landing page.
---

# 做一个好看、好用的页面

写第一行 HTML 之前读完这一份。它管的是观感和可读性；工程上怎么搭（应用清单、翻页逻辑）看对应的技能或用户的要求。

## 一、先判断要多大的排场

设计是默认要做的，要判断的只是做到哪一档：

- **务实档**（多数情况）：计划、报告、对照表、小工具、演示原型。要的是清楚的层级、讲究的间距、一套正经的配色。不要巨幅首屏，不要为了好看加东西。
- **表现档**：介绍页、小游戏、用户会长期留着或拿去给别人看的东西。这时才值得有鲜明的视觉个性，并且只在一处用力，其余保持安静。

拿不准就按务实档做。一个排得妥帖的页面永远不会错，一个用力过猛的页面经常会。

## 二、谁说了算

优先级固定：**用户的原话 > 已有的设计 > 你自己的选择**。

- 用户指定了风格、颜色、参考对象，就照做，哪怕它正好是下面「套路」里的一种。
- 动手前先找已有的设计：项目里的主题文件、样式变量、现成组件的写法。有就沿用，本文只补它没规定的部分。
- **Aide 侧栏应用**：配色一律用 Aide 铺到页面根元素上的主题变量（\`var(--aide-bg-base)\`、\`--aide-bg-raised\`、\`--aide-text-primary\`、\`--aide-text-secondary\`、\`--aide-border\`、\`--aide-accent\`、\`--aide-danger\`、\`--aide-success\`），不要自己定一套颜色。它是 Aide 的一部分，应该看起来就是 Aide 的一部分。

## 三、先定方案，再写页面

把方案直接写成样式表最顶上的 \`:root\` 变量块，后面所有样式都从它派生：

\`\`\`css
/* 布局：左侧固定筛选栏 + 右侧结果表，窄屏时筛选栏折到表格上方 */
:root {
  --bg: …; --surface: …; --text: …; --text-dim: …; --line: …; --accent: …;
  --font-body: …; --font-mono: …;
  --gap: 12px; --radius: 8px;
}
\`\`\`

- 颜色 4 到 6 个有名字的变量就够。正文里不再出现任何写死的颜色值。
- 布局思路用一行注释写在变量块上面。写不出这一行，说明还没想清楚。
- 这个方案是你的工作材料，不用向用户汇报色值和字体名；最多用一句话说明走的是什么方向。

## 四、内容从题材里来

- 用真实内容，不用占位的假字。数字带上它真实的单位和量级，术语用这个领域的人实际说的词。
- 至少有一处只属于这个题材的细节（记账页的金额右对齐并带千分位、接口工具的状态码着色、课表的节次）。它比任何装饰都更让页面显得用心。
- 序号、小标签、分隔线这类结构只在它说明了真实信息时才用。内容不是先后步骤，就不要编 01 / 02 / 03。

## 五、字

- **不要引外网字体。** 侧栏应用和单文件页面都加载不了，页面还可能被离线打开。用系统字体栈：
  正文 \`-apple-system, "Segoe UI", "PingFang SC", "Microsoft YaHei", "Noto Sans CJK SC", sans-serif\`；
  代码与数据 \`"Cascadia Code", "SF Mono", Consolas, "Noto Sans Mono CJK SC", monospace\`。
- 定一套字号阶梯（例如 12 / 13 / 15 / 20 / 28）并只用这几档，靠字号、字重、颜色深浅拉开层级。
- 成段的文字每行控制在 30 到 38 个汉字（英文约 65 个字符），行高 1.6 到 1.8。
- 成列对齐的数字加 \`font-variant-numeric: tabular-nums\`。

## 六、颜色与明暗

- 灰色不要用纯中性灰，向强调色的色相稍微偏一点，看起来才是选过的。
- 语义色（成功 / 警告 / 危险）和强调色是两回事，不要拿强调色表示状态。
- **独立页面要同时支持明暗**：\`:root\` 给一套完整的变量，再在 \`@media (prefers-color-scheme: dark)\` 里只重定义变量，组件样式不进媒体查询。\`body\` 必须显式设背景色。第二套主题不是简单反色，要重新确认对比度和强调色是否还成立。
- 侧栏应用不用自己处理明暗，用了主题变量就自动跟着走。
- 幻灯片可以只做一套，但背景和每一种文字颜色都要显式写出来。

## 七、布局

- 兄弟元素之间的间距用 flex / grid 的 \`gap\`，不要每个元素各写各的 margin。
- 窄了要能用：横排在窄屏时换行或叠成一列；装着长文字、代码、表格的 flex / grid 子项加 \`min-width: 0\`；只有表格、代码块、图表允许比屏幕宽，各自包一层 \`overflow-x: auto\`。页面本身不许横向滚动。
- **侧栏应用放在右栏时只有三百多像素宽**，按这个宽度设计，不要把桌面网页缩进去。需要多栏、表格、对照的，清单里选 \`main\`。
- 重复的元素（一排卡片、一列标签和值）保持同样的边距、基线和内边距，同一个部件在每一项里出现在同一个位置。
- 文字装不下时换行或在自己的容器里滚动。被截断看不全的文字是 bug。

## 八、克制

- 边框、底色、圆角、阴影，每一样都在说「这是一个独立的东西」。只给确实需要被区分出来的元素，不要每个区块都套同样的圆角加阴影，那样等于没有层级。
- 动效只在它帮上忙的地方用，一处编排好的过渡胜过处处都在动。尊重 \`prefers-reduced-motion\`。
- 能点的东西要看起来能点，键盘焦点要有看得见的样式。

## 九、打开就是完整的

- 要给人看的内容，页面加载完就都在，不要等滚动到才出现，更不要停在 \`opacity: 0\` 等脚本。
- 工具类页面打开就处在一个真实的工作状态：有用户的数据就用，没有就放几条示例并明说是示例。只有空壳和输入框的首屏，什么都没展示。
- 空状态要设计：告诉用户这里将来会出现什么、怎么加第一条。

## 十、文案

- 站在用的人那一边命名：他认得的词，而不是程序内部的叫法。
- 按钮写清楚它会做什么（「保存」「删除这一条」），做完的反馈用同一个词（「已保存」）。
- 报错说明出了什么问题、怎么解决，不道歉、不含糊。
- 页面标题是一个名字（两到四个词，具体到能认出这个页面），不是一句说明。

## 十一、别做成套路

没有被指定风格时，避开这些一眼能认出是机器生成的样子：

- 奶油色底配衬线大标题和陶土色点缀
- 近黑底上孤零零一个荧光绿或朱红
- 白底上一个紫到蓝渐变的首屏
- emoji 当小节标记
- 所有东西居中
- 到处都是同一个圆角
- 圆角卡片左侧贴一条强调色竖条

## 十二、三类产出各自要注意的

**侧栏应用界面**（工程约束见 aide-app 技能）
- 颜色只用 Aide 主题变量；字号以 12 到 13px 为基准，与 Aide 自身的密度一致。
- 所有依赖放进应用文件夹，CDN 加载不了。
- 图标、角标、提示这些交给 Aide 提供的能力，不要在页面里再造一套。

**幻灯片**（单文件 HTML）
- 一页只讲一件事。标题是这一页的结论，不是话题名。
- 16:9 画布按比例缩放铺满窗口；正文字号不小于画布高度的 3%，坐在后排也能看清。
- 每页的标题、页码、留白位置一致；全片只用一套配色和两档字重。
- 要点不超过五条，能用一张图或一个大数字说明的就不要列条目。

**独立页面**（报告、原型、介绍页）
- 单文件：样式和脚本内联，图片用 data URI 或放在同目录，断网也能打开。
- 支持明暗两套，手机宽度下可读。
- 长文档给一个能跳转的目录；数据页先给结论再给明细。

## 十三、交付前过一遍

写完后对照检查一次，有条件就在浏览器里看一眼，然后交付。不要反复截图微调，后续打磨等用户提出来再做。

- 样式里还有没有写死的颜色？
- 窄屏下有没有横向滚动、有没有被截断的文字？
- 明暗两套（或 Aide 的几个主题）下文字都看得清吗？
- 首屏是不是一个完整的、有内容的状态？
- 有没有哪一处只是为了「显得有设计」而存在？有就删掉。
`;

/** 幂等落地，失败静默（见 builtinSkill.ts）。 */
export function ensureDesignSkill(env: SkillEnv): void {
  ensureBuiltinSkill(env, SKILL_NAME, DESIGN_SKILL_CONTENT);
}
